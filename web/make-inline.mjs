// Writes web/inline.js: a classic-script copy of calc.js plus presets.json.
// Also copies calc.js byte for byte to skills/hustle-check/calc.js so the skill runs the same math.
// Why: browsers block ES module imports and fetch() on file://, and the page must open from a file.
// Run after editing calc.js or presets.json: node web/make-inline.mjs  (calc.test.js fails if you forget)
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (name) => fileURLToPath(new URL(name, import.meta.url));

export function buildInline() {
  const calc = readFileSync(here("calc.js"), "utf8").replace(/\r\n/g, "\n").replace(/^export /gm, "");
  const presets = JSON.stringify(JSON.parse(readFileSync(here("presets.json"), "utf8")));
  return [
    "// Generated by make-inline.mjs from calc.js and presets.json. Do not edit by hand.",
    "(function () {",
    '"use strict";',
    calc.trim(),
    "window.HustleCalc = { facets, scale, toolsCost, isBusiness, matchHustle, closest, validate, encode, decode };",
    `window.HustlePresets = ${presets};`,
    "})();",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(here("inline.js"), buildInline());
  copyFileSync(here("calc.js"), here("../skills/hustle-check/calc.js"));
  console.log("wrote web/inline.js and skills/hustle-check/calc.js");
}
